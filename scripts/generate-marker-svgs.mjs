import { writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as fa6 from "react-icons/fa6";
import * as io from "react-icons/io";
import * as sl from "react-icons/sl";
const list = [
  ["pin", "FaLocationDot", fa6],
  ["heart", "FaHeart", fa6],
  ["home", "FaHouse", fa6],
  ["star", "FaStar", fa6],
  ["circle", "FaCircle", fa6],
  ["square", "FaSquare", fa6],
  ["x", "FaXmark", fa6],
  ["target", "SlTarget", sl],
  ["sun", "FaSun", fa6],
  ["moon", "FaMoon", fa6],
  ["building", "FaBuilding", fa6],
  ["send", "FaPaperPlane", fa6],
  ["snowflake", "FaRegSnowflake", fa6],
  ["shop", "FaShop", fa6],
  ["camera", "FaCamera", fa6],
  ["flower", "IoMdFlower", io],
  ["tree", "FaTree", fa6],
  ["flag", "FaFlag", fa6],
];
const out = {};
for (const [id, name, mod] of list)
  out[id] = renderToStaticMarkup(
    createElement(mod[name], { size: 24, color: "currentColor", "aria-hidden": true }),
  );
const body = Object.entries(out)
  .map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)},`)
  .join("\n");
writeFileSync(
  new URL("../src/services/markers/iconSvgs.ts", import.meta.url),
  `// Generated by scripts/generate-marker-svgs.mjs — do not edit by hand.\n// Pre-rendered so the browser bundle does not need react-dom/server.\nexport const MARKER_ICON_SVGS: Record<string, string> = {\n${body}\n};\n`,
);
